#!/usr/bin/env python3
"""Exercise a remote Kokoro speech endpoint and measure WAV generation speed."""

import argparse
import io
import json
from pathlib import Path
import time
from urllib.request import Request, urlopen
import wave


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("base_url", help="API base URL, including /v1")
    parser.add_argument("--voice", default="af_heart")
    parser.add_argument("--text-file", type=Path)
    parser.add_argument("--output", type=Path, default=Path("kokoro-sample.wav"))
    args = parser.parse_args()
    text = args.text_file.read_text() if args.text_file else (
        "Hello. This audio was generated by your Kokoro server, "
        "and downloaded over the local network. "
        "The article service can run on a different machine."
    )
    base = args.base_url.rstrip("/")
    with urlopen(base + "/audio/voices", timeout=30) as response:
        voices = json.load(response)
    print(f"Voices endpoint: HTTP 200 ({len(voices['voices'])} voices)", flush=True)
    request = Request(base + "/audio/speech", data=json.dumps({
        "model": "kokoro", "voice": args.voice, "input": text,
        "response_format": "wav", "speed": 1.0, "stream": False,
    }).encode(), headers={"Content-Type": "application/json"})
    started = time.monotonic()
    with urlopen(request, timeout=600) as response:
        audio = response.read()
    elapsed = time.monotonic() - started
    with wave.open(io.BytesIO(audio)) as wav:
        # Streaming WAV headers can declare a placeholder rather than the final size.
        pcm = wav.readframes(wav.getnframes())
        channels = wav.getnchannels()
        sample_width = wav.getsampwidth()
        sample_rate = wav.getframerate()
        duration = len(pcm) / (channels * sample_width * sample_rate)
    if duration <= 0:
        raise RuntimeError("Endpoint returned empty audio")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    with wave.open(str(args.output), "wb") as wav:
        wav.setnchannels(channels)
        wav.setsampwidth(sample_width)
        wav.setframerate(sample_rate)
        wav.writeframes(pcm)
    print(json.dumps({
        "voice": args.voice, "characters": len(text), "words": len(text.split()),
        "request_seconds": round(elapsed, 2), "audio_seconds": round(duration, 2),
        "speed_vs_realtime": round(duration / elapsed, 2),
        "sample_rate": sample_rate, "output": str(args.output),
    }, indent=2))


if __name__ == "__main__":
    main()
